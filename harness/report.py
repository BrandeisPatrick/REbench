"""Compile every pilot run into runs/RESULTS.md (no model calls)."""
import glob, json, os
RB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows, perf_rows = [], []
for rd in sorted(glob.glob(f"{RB}/runs/pilot-*") + glob.glob(f"{RB}/runs/sealed-*") + glob.glob(f"{RB}/runs/rust-*")):
    if not os.path.isdir(rd):
        continue
    try:
        m = json.load(open(f"{rd}/meta.json"))
    except Exception:
        continue
    if "process" not in m and os.path.exists(f"{rd}/summary.json"):  # sealed runs keep process metrics in summary.json
        m["process"] = json.load(open(f"{rd}/summary.json")).get("process", {})
    if "driver" not in m:
        m["audit"] = {"violation_count": "sealed"}
    sub = f"{rd}/submission"
    files = [os.path.join(r, f) for r, _, fs in os.walk(sub) for f in fs]
    lang = ("Go" if any(f.endswith(".go") for f in files) else "Rust" if any(f.endswith(".rs") for f in files)
            else "C/C++" if any(f.endswith((".c", ".cc", ".cpp")) for f in files) else "Python" if any(f.endswith(".py") for f in files) else "?")
    loc = sum(sum(1 for _ in open(f, errors="ignore")) for f in files if f.endswith((".go", ".rs", ".c", ".cc", ".cpp", ".h", ".py", ".js")))
    for g in sorted(glob.glob(f"{rd}/grade-*/reward.json")):
        ev = os.path.basename(os.path.dirname(g))[6:]
        r = json.load(open(g)); s = r.get("score", {}); c = r.get("correctness") or {}
        a = m.get("audit", {})
        rows.append(f"| {ev} | {os.path.basename(rd)} | {m['model']} | {lang} | {loc} | {m.get('wall_minutes')} of {m['minutes']} | "
                    f"{c.get('cell_match_rate', 0):.2%} | {c.get('books_perfect', 0)}/{c.get('books', 0)} | {'yes' if s.get('resolved') else 'no'} | "
                    f"{s.get('E', 0):.2f}x | {s.get('task_score', 0):.3f} | {m.get('process', {}).get('tool_calls')} / {m.get('process', {}).get('gui_actions')} | "
                    f"{a.get('violation_count', '?')} | {'; '.join(r.get('hard_fail') or []) or 'none'} |")
        for k, v in (r.get("performance") or {}).items():
            perf_rows.append(f"| {ev} | {os.path.basename(rd)} | {k} | {v.get('match_rate', 0):.4f} | {v.get('wall_4core_s', float('nan')):.3f} | "
                             f"{v.get('baseline_4core_s', float('nan')):.3f} | {v.get('speedup_vs_lo', 0):.2f}x | {v.get('parallel_speedup', float('nan')):.2f} | "
                             f"{v.get('peak_rss_mb', float('nan')):.0f} |")
out = ["# Rebuild Bench results (calc task)", "",
       "Generated by harness/report.py. Score = correctness gate (>=99.9% cells and >=95% books) then speed vs LibreOffice "
       "(parity 0.5, 8x faster 1.0). E = geometric-mean speedup, with workloads under 99.9% correct counted as 1/8.", "",
       "| eval set | run | model | language | LOC | minutes used | hidden cells correct | books fully correct | gate | E | score | sbx calls / GUI actions | audit flags | hard fail |",
       "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"] + rows + ["", "## Performance workloads", "",
       "| eval set | run | workload | cells correct | rebuild s (4 cores) | LibreOffice s | speedup | 1-core / 4-core | peak RSS MB |",
       "|---|---|---|---|---|---|---|---|---|"] + perf_rows
open(f"{RB}/runs/RESULTS.md", "w").write("\n".join(out) + "\n")
print("\n".join(out))
